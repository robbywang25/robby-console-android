#!/bin/bash
# Cloud-session setup: install Tailscale + adb, join the tailnet, and get ready
# for adb wireless debugging against an Android device on the same tailnet.
#
# Optional environment variables (set in the cloud environment settings):
#   TS_AUTHKEY      Tailscale auth key (ephemeral + reusable recommended). Without it,
#                   run `tailscale up` manually and open the printed login URL.
#   TS_HOSTNAME     Node name on the tailnet (default: claude-cloud).
#   ADB_KEY_B64     base64 of an adb private key (e.g. `base64 -i ~/.android/adbkey`
#                   on a machine the phone already trusts), so no re-pairing is needed.
#   ADB_TARGET      host:port to `adb connect` to once the tailnet is up.
set -euo pipefail

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

TS_VERSION="1.104.2"
TS_SHA256="512f613ed7d04fc7282f7dc5bd76aa105aae28168fbb9357eb749ebcbc29f0ae"
TS_SOCKET="/var/run/tailscale/tailscaled.sock"

log() { echo "[session-start] $*" >&2; }

install_tailscale() {
  if command -v tailscaled >/dev/null && tailscale version 2>/dev/null | head -1 | grep -qx "$TS_VERSION"; then
    return
  fi
  log "installing Tailscale $TS_VERSION"
  local tmp tgz="tailscale_${TS_VERSION}_amd64.tgz"
  tmp="$(mktemp -d)"
  curl -fsSL -o "$tmp/$tgz" "https://pkgs.tailscale.com/stable/$tgz"
  echo "$TS_SHA256  $tmp/$tgz" | sha256sum -c --quiet -
  tar -xzf "$tmp/$tgz" -C "$tmp"
  install -m755 "$tmp/tailscale_${TS_VERSION}_amd64/tailscale" "$tmp/tailscale_${TS_VERSION}_amd64/tailscaled" /usr/local/bin/
  rm -rf "$tmp"
}

install_adb() {
  if [ -x /opt/platform-tools/adb ]; then
    ln -sf /opt/platform-tools/adb /usr/local/bin/adb
    return
  fi
  log "installing Android platform-tools"
  local tmp
  tmp="$(mktemp -d)"
  curl -fsSL -o "$tmp/pt.zip" https://dl.google.com/android/repository/platform-tools-latest-linux.zip
  python3 -I -m zipfile -e "$tmp/pt.zip" /opt/
  chmod +x /opt/platform-tools/adb /opt/platform-tools/fastboot
  ln -sf /opt/platform-tools/adb /usr/local/bin/adb
  rm -rf "$tmp"
}

start_tailscaled() {
  if tailscale --socket="$TS_SOCKET" status >/dev/null 2>&1 || pgrep -x tailscaled >/dev/null; then
    return
  fi
  log "starting tailscaled"
  mkdir -p /var/run/tailscale
  # In-memory state: every container is a fresh node, so a cached container
  # snapshot never carries (and shares) a node identity.
  nohup tailscaled --state=mem: --socket="$TS_SOCKET" >/var/log/tailscaled.log 2>&1 &
  for _ in $(seq 1 20); do
    tailscale --socket="$TS_SOCKET" version >/dev/null 2>&1 && \
      tailscale --socket="$TS_SOCKET" status --json >/dev/null 2>&1 && break
    sleep 0.5
  done
}

join_tailnet() {
  if [ -z "${TS_AUTHKEY:-}" ]; then
    log "TS_AUTHKEY not set; run: tailscale up --hostname=${TS_HOSTNAME:-claude-cloud} --accept-dns=false"
    return
  fi
  log "joining tailnet as ${TS_HOSTNAME:-claude-cloud}"
  timeout 45 tailscale --socket="$TS_SOCKET" up --authkey="$TS_AUTHKEY" \
    --hostname="${TS_HOSTNAME:-claude-cloud}" --accept-dns=false --timeout=40s \
    || log "tailscale up failed; see /var/log/tailscaled.log"
}

setup_adb_key() {
  [ -n "${ADB_KEY_B64:-}" ] || return 0
  mkdir -p ~/.android
  if [ ! -s ~/.android/adbkey ]; then
    echo "$ADB_KEY_B64" | base64 -d > ~/.android/adbkey
    chmod 600 ~/.android/adbkey
    rm -f ~/.android/adbkey.pub  # regenerated by adb from the private key
  fi
}

connect_adb() {
  [ -n "${ADB_TARGET:-}" ] || return 0
  timeout 20 adb connect "$ADB_TARGET" >&2 || log "adb connect $ADB_TARGET failed"
}

install_tailscale
install_adb
setup_adb_key
start_tailscaled
join_tailnet
connect_adb
